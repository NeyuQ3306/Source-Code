package learning.collection;

public class QueueLearning {
    /*
        Cấu trúc dữ liệu hàng đợi Queue trong Java:
     Hay dùng 2 loại là Queue và Deque
     - Cú pháp:
        Queue<KDL Object> q = new ArrayDeque<>();
        Deque<KDL Object> dq = new ArrayDeque<>();

     - Các hàm thông dụng Queue:
        | Hàm           | Tác dụng                   | Ví dụ            |
        | ------------- | -------------------------- | ---------------- |
        | `offer(x)`    | Thêm `x` vào cuối          | `q.offer(10)`    |
        | `poll()`      | Lấy + xóa phần tử đầu      | `q.poll()`       |
        | `peek()`      | Xem phần tử đầu, không xóa | `q.peek()`       |
        | `add(x)`      | Thêm `x` vào cuối          | `q.add(10)`      |
        | `remove()`    | Lấy + xóa đầu              | `q.remove()`     |
        | `element()`   | Xem phần tử đầu            | `q.element()`    |
        | `isEmpty()`   | Kiểm tra rỗng              | `q.isEmpty()`    |
        | `size()`      | Số lượng phần tử           | `q.size()`       |
        | `contains(x)` | Kiểm tra `x` có tồn tại    | `q.contains(10)` |
        | `clear()`     | Xóa toàn bộ                | `q.clear()`      |

    - Các hàm thông dụng Deque:
        | Hàm             | Tác dụng       |
        | --------------- | -------------- |
        | `offerFirst(x)` | Thêm vào đầu   |
        | `offerLast(x)`  | Thêm vào cuối  |
        | `pollFirst()`   | Lấy + xóa đầu  |
        | `pollLast()`    | Lấy + xóa cuối |
        | `peekFirst()`   | Xem đầu        |
        | `peekLast()`    | Xem cuối       |

    */
}
